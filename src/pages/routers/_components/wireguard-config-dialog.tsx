import { useState } from "react";
import type { Doc } from "@/convex/_generated/dataModel.d.ts";
import { buildWireGuardConfig, downloadTextFile } from "./wireguard-keygen.ts";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from "@/components/ui/dialog.tsx";
import { Button } from "@/components/ui/button.tsx";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs.tsx";
import { Badge } from "@/components/ui/badge.tsx";
import { Copy, Check, Download, Eye, EyeOff } from "lucide-react";

type Props = {
  router: Doc<"routers">;
  open: boolean;
  onOpenChange: (v: boolean) => void;
};

/**
 * Build a fully copy-paste-ready MikroTik RouterOS provisioning script.
 * No placeholder tokens — every value comes from the stored router record.
 */
function buildMikroTikScript(router: Doc<"routers">): string {
  const osVersion = router.routerOsVersion ?? "v7";

  // Extract endpoint host/port
  const lastColon = router.serverEndpoint.lastIndexOf(":");
  const endpointHost =
    lastColon !== -1 ? router.serverEndpoint.slice(0, lastColon) : router.serverEndpoint;
  const endpointPort = lastColon !== -1 ? router.serverEndpoint.slice(lastColon + 1) : "51820";

  // Strip CIDR from tunnel IP for the address assignment
  const tunnelIpOnly = router.tunnelIp.split("/")[0];
  const serverTunnelIpOnly = router.serverTunnelIp.split("/")[0];

  // RADIUS server IP — derived from serverTunnelIp (the server side of the tunnel)
  const radiusServerIp = serverTunnelIpOnly;

  const pskLine = router.presharedKey
    ? `  preshared-key="${router.presharedKey}" \\\n`
    : "";

  if (osVersion === "v7") {
    return `# ============================================================
# MikroTik RouterOS v7 — Auto-Provisioning Script
# Router : ${router.name}
# NAS-ID : ${router.nasIdentifier}
# Generated by ISP Billing System
# ============================================================
# Run in: Terminal  OR  Winbox > New Terminal  OR  paste in
#         System > Scripts  then run it.
# ============================================================

# ── 1. Set router identity ──────────────────────────────────
/system identity set name="${router.nasIdentifier}"

# ── 2. WireGuard interface ──────────────────────────────────
/interface wireguard add \\
  name=wg-billing \\
  listen-port=51820 \\
  private-key="${router.privateKey}" \\
  comment="Billing tunnel"

# ── 3. Tunnel IP address ────────────────────────────────────
/ip address add \\
  address="${router.tunnelIp}" \\
  interface=wg-billing \\
  comment="WireGuard tunnel IP"

# ── 4. WireGuard peer (billing server) ─────────────────────
/interface wireguard peers add \\
  interface=wg-billing \\
  public-key="${router.serverPublicKey}" \\
${pskLine}  endpoint-address="${endpointHost}" \\
  endpoint-port=${endpointPort} \\
  allowed-address="${router.allowedIPs}" \\
  persistent-keepalive=25s \\
  comment="Billing server peer"

# ── 5. RADIUS server (points to billing server via tunnel) ──
/radius add \\
  service=ppp,login,hotspot \\
  address=${radiusServerIp} \\
  secret="${router.radiusSecret}" \\
  timeout=3000ms \\
  comment="Billing RADIUS"

# ── 6. PPP profile with RADIUS ──────────────────────────────
/ppp profile add \\
  name=pppoe-billing \\
  use-radius=yes \\
  change-tcp-mss=yes \\
  comment="PPPoE profile — RADIUS managed"

# ── 7. PPPoE server (adjust interface to your WAN/LAN) ──────
/interface pppoe-server server add \\
  interface=ether1 \\
  service-name=pppoe \\
  default-profile=pppoe-billing \\
  one-session-per-host=yes \\
  disabled=no

# ── 8. Optional: Hotspot RADIUS (if using hotspot) ──────────
# /ip hotspot profile set default login-by=radius radius-accounting=yes

# ── Done ─────────────────────────────────────────────────────
:log info "Billing tunnel provisioned — ${router.name}"
:put "Provisioning complete. Tunnel IP: ${tunnelIpOnly} -> ${radiusServerIp}"
`;
  }

  // RouterOS v6
  return `# ============================================================
# MikroTik RouterOS v6 — Auto-Provisioning Script
# Router : ${router.name}
# NAS-ID : ${router.nasIdentifier}
# NOTE   : WireGuard package must be installed on v6.
#          Download from mikrotik.com/download (Extra packages)
# Generated by ISP Billing System
# ============================================================
# Run in: Terminal  OR  Winbox > New Terminal
# ============================================================

# ── 1. Set router identity ──────────────────────────────────
/system identity set name="${router.nasIdentifier}"

# ── 2. WireGuard interface ──────────────────────────────────
/interface wireguard add \\
  name=wg-billing \\
  listen-port=51820 \\
  private-key="${router.privateKey}" \\
  comment="Billing tunnel"

# ── 3. Tunnel IP address ────────────────────────────────────
/ip address add \\
  address="${router.tunnelIp}" \\
  interface=wg-billing \\
  comment="WireGuard tunnel IP"

# ── 4. WireGuard peer (billing server) ─────────────────────
/interface wireguard peers add \\
  interface=wg-billing \\
  public-key="${router.serverPublicKey}" \\
${pskLine}  endpoint-address="${endpointHost}" \\
  endpoint-port=${endpointPort} \\
  allowed-address="${router.allowedIPs}" \\
  persistent-keepalive=25s \\
  comment="Billing server peer"

# ── 5. RADIUS server (points to billing server via tunnel) ──
/radius add \\
  service=ppp,login,hotspot \\
  address=${radiusServerIp} \\
  secret="${router.radiusSecret}" \\
  timeout=3000ms \\
  comment="Billing RADIUS"

# ── 6. PPP profile with RADIUS ──────────────────────────────
/ppp profile add \\
  name=pppoe-billing \\
  use-radius=yes \\
  change-tcp-mss=yes \\
  comment="PPPoE profile — RADIUS managed"

# ── 7. PPPoE server (adjust interface to your WAN/LAN) ──────
/interface pppoe-server server add \\
  interface=ether1 \\
  service-name=pppoe \\
  default-profile=pppoe-billing \\
  one-session-per-host=yes \\
  disabled=no

# ── 8. Optional: Hotspot RADIUS (if using hotspot) ──────────
# /ip hotspot profile set default login-by=radius radius-accounting=yes

# ── Done ─────────────────────────────────────────────────────
:log info "Billing tunnel provisioned — ${router.name}"
:put "Provisioning complete. Tunnel IP: ${tunnelIpOnly} -> ${radiusServerIp}"
`;
}

export default function WireGuardConfigDialog({ router, open, onOpenChange }: Props) {
  const [copied, setCopied] = useState<string | null>(null);
  const [showPrivateKey, setShowPrivateKey] = useState(false);

  const conf = buildWireGuardConfig({
    privateKey: router.privateKey,
    tunnelIp: router.tunnelIp,
    dns: router.dns,
    serverPublicKey: router.serverPublicKey,
    serverEndpoint: router.serverEndpoint,
    serverTunnelIp: router.serverTunnelIp,
    allowedIPs: router.allowedIPs,
    presharedKey: router.presharedKey,
  });

  const mikrotikScript = buildMikroTikScript(router);
  const osVersion = router.routerOsVersion ?? "v7";

  const copy = async (text: string, key: string) => {
    await navigator.clipboard.writeText(text);
    setCopied(key);
    setTimeout(() => setCopied(null), 2000);
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-2xl max-h-[90vh] overflow-y-auto">
        <DialogHeader>
          <DialogTitle>Provisioning — {router.name}</DialogTitle>
          <DialogDescription>
            Copy the script and paste it into MikroTik Terminal or Winbox. All values are pre-filled — no edits needed.
          </DialogDescription>
        </DialogHeader>

        <Tabs defaultValue="mikrotik">
          <TabsList className="w-full">
            <TabsTrigger value="mikrotik" className="flex-1">MikroTik Script</TabsTrigger>
            <TabsTrigger value="wgconf" className="flex-1">wg.conf</TabsTrigger>
            <TabsTrigger value="keys" className="flex-1">Keys</TabsTrigger>
          </TabsList>

          {/* ── MikroTik Script ── */}
          <TabsContent value="mikrotik" className="space-y-3 pt-4">
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-2">
                <Badge variant="outline" className="text-xs border-primary/30 text-primary">
                  RouterOS {osVersion}
                </Badge>
                <span className="text-xs text-muted-foreground">Ready to paste — no placeholders</span>
              </div>
              <div className="flex gap-2">
                <Button variant="secondary" size="sm" onClick={() => copy(mikrotikScript, "mikrotik")}>
                  {copied === "mikrotik" ? <Check className="w-3.5 h-3.5 mr-1.5 text-green-500" /> : <Copy className="w-3.5 h-3.5 mr-1.5" />}
                  Copy
                </Button>
                <Button size="sm" onClick={() => downloadTextFile(`${router.nasIdentifier}-setup.rsc`, mikrotikScript)}>
                  <Download className="w-3.5 h-3.5 mr-1.5" />
                  Download .rsc
                </Button>
              </div>
            </div>

            <div className="rounded-lg border border-primary/20 bg-primary/5 p-3 text-xs space-y-1">
              <p className="font-medium text-foreground">How to run</p>
              <ol className="list-decimal list-inside space-y-0.5 text-muted-foreground">
                <li>Open Winbox → connect to your router</li>
                <li>Click <strong className="text-foreground">New Terminal</strong></li>
                <li>Paste the entire script and press <kbd className="bg-muted px-1 rounded">Enter</kbd></li>
                <li>Confirm the tunnel is up: <code className="bg-muted px-1 rounded">/interface wireguard print</code></li>
              </ol>
              {osVersion === "v6" && (
                <p className="text-amber-500 font-medium mt-1">
                  RouterOS v6: install the WireGuard extra package first from mikrotik.com/download
                </p>
              )}
            </div>

            <pre className="rounded-lg bg-muted/50 border p-4 text-xs font-mono whitespace-pre-wrap overflow-auto max-h-96 leading-relaxed">
              {mikrotikScript}
            </pre>
          </TabsContent>

          {/* ── wg.conf ── */}
          <TabsContent value="wgconf" className="space-y-3 pt-4">
            <p className="text-xs text-muted-foreground">Standard WireGuard config — useful for non-MikroTik peers or documentation.</p>
            <div className="flex justify-end gap-2">
              <Button variant="secondary" size="sm" onClick={() => copy(conf, "conf")}>
                {copied === "conf" ? <Check className="w-3.5 h-3.5 mr-1.5 text-green-500" /> : <Copy className="w-3.5 h-3.5 mr-1.5" />}
                Copy
              </Button>
              <Button size="sm" onClick={() => downloadTextFile(`${router.nasIdentifier}-wg.conf`, conf)}>
                <Download className="w-3.5 h-3.5 mr-1.5" />
                Download .conf
              </Button>
            </div>
            <pre className="rounded-lg bg-muted/50 border p-4 text-xs font-mono whitespace-pre-wrap overflow-auto max-h-80">
              {conf}
            </pre>
          </TabsContent>

          {/* ── Keys ── */}
          <TabsContent value="keys" className="space-y-4 pt-4">
            <div className="space-y-3">
              <KeyRow label="Router Public Key" value={router.publicKey} copyKey="pub" copied={copied} onCopy={copy} />
              <KeyRow
                label="Router Private Key"
                value={router.privateKey}
                copyKey="priv"
                copied={copied}
                onCopy={copy}
                masked={!showPrivateKey}
                toggleMask={() => setShowPrivateKey((v) => !v)}
              />
              {router.presharedKey && (
                <KeyRow label="Preshared Key" value={router.presharedKey} copyKey="psk" copied={copied} onCopy={copy} />
              )}
              <KeyRow label="Server Public Key" value={router.serverPublicKey} copyKey="servpub" copied={copied} onCopy={copy} />
              <KeyRow label="RADIUS Shared Secret" value={router.radiusSecret} copyKey="radius" copied={copied} onCopy={copy} masked />
            </div>
          </TabsContent>
        </Tabs>
      </DialogContent>
    </Dialog>
  );
}

function KeyRow({
  label,
  value,
  copyKey,
  copied,
  onCopy,
  masked = false,
  toggleMask,
}: {
  label: string;
  value: string;
  copyKey: string;
  copied: string | null;
  onCopy: (text: string, key: string) => void;
  masked?: boolean;
  toggleMask?: () => void;
}) {
  return (
    <div className="space-y-1">
      <p className="text-xs font-medium text-muted-foreground">{label}</p>
      <div className="flex items-center gap-2 rounded-lg border bg-muted/30 px-3 py-2">
        <code className="flex-1 text-xs font-mono text-foreground break-all">
          {masked ? "••••••••••••••••••••••••••••••••••••••••••••" : value}
        </code>
        {toggleMask && (
          <button onClick={toggleMask} className="text-muted-foreground hover:text-foreground shrink-0 cursor-pointer">
            {masked ? <Eye className="w-3.5 h-3.5" /> : <EyeOff className="w-3.5 h-3.5" />}
          </button>
        )}
        <button onClick={() => onCopy(value, copyKey)} className="text-muted-foreground hover:text-foreground shrink-0 cursor-pointer">
          {copied === copyKey ? <Check className="w-3.5 h-3.5 text-green-500" /> : <Copy className="w-3.5 h-3.5" />}
        </button>
      </div>
    </div>
  );
}
